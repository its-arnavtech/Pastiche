"""`remixer` command line. Subcommands are contributed by modules that define `register(sub)`.

To add a command group, append its module to COMMAND_MODULES; missing modules are skipped,
so agents can land their lanes independently.
"""
from __future__ import annotations

import argparse
import importlib
import json
import logging
import multiprocessing as mp
import os
import sys

from remixer import PROJECT_NAME, __version__

COMMAND_MODULES = [
    "remixer.gpu.cli",        # separate, embed, taste, musicgen (opus-cc)
    "remixer.telemetry.cli",  # telemetry run|dashboard (opus-cc)
    "remixer.bench.cli",      # bench stress (opus-cc)
    "remixer.adapters.insight_job",  # insights nightly (opus-cc)
    "remixer.server.app",     # serve: FastAPI player backend (opus-cc)
    "remixer.corpus.cli",     # corpus generate (gpt-sol)
    "remixer.cpu.cli",        # analyze, assemble, render (gpt-sol)
    "remixer.npu.cli",        # npu (gpt-sol)
    "remixer.synth.cli",      # synth (gpt-sol)
    "remixer.events.cli",     # events, heatmap (cursor-opus)
    "remixer.player.cli",     # player (cursor-opus)
]


def cmd_info(args) -> None:
    from remixer.adapters import build

    a = build()
    p = a.profile
    out = {
        "project": PROJECT_NAME, "version": __version__, "profile": p["name"], "mode": p.mode,
        "data_dir": str(p.data_dir),
        "resources": {"logical": p.resources.logical_cores, "physical": p.resources.physical_cores,
                      "gpu_feeders": p.resources.gpu_feeders, "cpu_workers": p.resources.cpu_workers,
                      "reserve": p.resources.reserve},
        "devices": [{"name": d.name, "kind": d.kind, "total_gb": round(d.total_memory / 1e9, 2),
                     "free_gb": round(d.free_memory / 1e9, 2)} for d in a.compute.devices()],
        "jobs": a.jobs.counts(),
    }
    print(json.dumps(out, indent=2))


def cmd_resources(args) -> None:
    import psutil

    from remixer.adapters.local_compute import nvml_handle
    from remixer.config import REPO_ROOT, compute_resources, resources_yaml

    res = compute_resources({"reserve": {"logical_cores": args.reserve}, "gpu_lane": {"feeder_cores": args.feeders}})
    vram = 0.0
    if (h := nvml_handle()) is not None:
        import pynvml
        vram = pynvml.nvmlDeviceGetMemoryInfo(h).total / 2**30
    text = resources_yaml(res, psutil.virtual_memory().total / 2**30, vram)
    if args.write:
        (REPO_ROOT / "config" / "resources.yaml").write_text(
            "# Generated by `remixer resources --write` from this machine's real core count.\n" + text,
            encoding="utf-8")
    print(text)


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="remixer", description=f"{PROJECT_NAME} POC 1")
    ap.add_argument("--safe", action="store_true", help="conservative guards (battery pause, GPU 90 C / CPU 100 C)")
    ap.add_argument("--unleashed", action="store_true",
                    help="lift the stable preset's caps (default: 8 CPU workers, light Demucs, batch <= 8, NPU only, "
                         "thermal watchdog). Two uncapped runs shut this laptop down: prints a warning")
    ap.add_argument("-v", "--verbose", action="store_true")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("info", help="profile, resources, devices, queue").set_defaults(fn=cmd_info)
    r = sub.add_parser("resources", help="recompute lane budgets from the real core count")
    r.add_argument("--reserve", type=int, default=1)
    r.add_argument("--feeders", type=int, default=4)
    r.add_argument("--write", action="store_true")
    r.set_defaults(fn=cmd_resources)
    for name in COMMAND_MODULES:
        try:
            mod = importlib.import_module(name)
        except ModuleNotFoundError as e:
            if e.name and (name == e.name or name.startswith(e.name + ".")):
                continue  # lane not landed yet
            raise
        mod.register(sub)
    return ap


def main(argv: list[str] | None = None) -> None:
    mp.set_start_method("spawn", force=True)
    args = build_parser().parse_args(argv)
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO,
                        format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    if args.safe:
        os.environ["REMIXER_SAFE"] = "1"
    if args.unleashed:
        from remixer.presets import enable_unleashed

        enable_unleashed()
    from remixer.adapters.local_compute import pin_from_env

    if cores := pin_from_env():  # set per lane by `bench stress`; worker processes inherit the mask
        logging.getLogger("remixer").info("pinned to logical CPUs %s", cores)
    sys.exit(args.fn(args) or 0)


if __name__ == "__main__":
    main()
